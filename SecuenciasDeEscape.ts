// secuencias de escape

"\'" // comillas simples ejemplo: 'Hola, soy un texto con comillas simples: \'Esto es una comilla simple\''
"\"" // comillas dobles ejemplo: "Hola, soy un texto con comillas dobles: \"Esto es una comilla doble\""
"\\" // barra invertida ejemplo: "Hola, soy un texto con una barra invertida: \\ Esto es una barra invertida"
"\n" // salto de linea ejemplo: "Hola, soy un texto con un salto de linea: \nEsto es una nueva linea"
"\r" // tabulacion     ejemplo: "Hola, soy un texto con una tabulacion: \rEsto es una tabulacion"
"\t" // salto de linea ejemplo: "Hola, soy un texto con un salto de linea: \tEsto es una nueva linea con tabulacion"
"\b" // retroceso      ejemplo: "Hola, soy un texto con un retroceso: \bEsto es un retroceso"
"\f" // avance de pagina ejemplo: "Hola, soy un texto con un avance de pagina: \fEsto es un avance de pagina"

let numeroDia = 2;

if (numeroDia === 1) {
  console.log("Lunes");
} else if (numeroDia === 2) {
  console.log("Martes");
} else if (numeroDia === 3) {
  console.log("Miércoles");
} else {
  console.log("Día desconocido");
}

let valorDia = 2;

switch (valorDia) {
  case 1:
    console.log("Lunes");
    break;

  case 2:
    console.log("Martes");
    break;

  case 3:
    console.log("Miércoles");
    break;

  default:
    console.log("Día desconocido");
}
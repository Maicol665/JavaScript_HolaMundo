let Suma = 6 + 3;
console.log("Suma:", Suma);

let Resta = 6 - 3;
console.log("Resta:", Resta);

// multiplicacion y division
let Multiplicacion = 6 * 3;
console.log("Multiplicacion:", Multiplicacion);

let Division = 6 / 3;
console.log("Division:", Division);


// Decimales
let NumeroDecimal = 5.53;
console.log("NumeroDecimal:", NumeroDecimal);

// Incrementar el valor de una variable
let LibrosComprados = 5;

console.log("LibrosComprados:", LibrosComprados);

LibrosComprados = LibrosComprados + 1;
console.log("LibrosComprados después de comprar otro libro:", LibrosComprados);

// Otra forma de incrementar el valor de una variable es utilizando el operador de asignación compuesto +=

let a = 23;
a += 5; // Esto es equivalente a a = a + 5
console.log("Valor de a después de incrementar en 5:", a);

let TotalVntas = 100.5;
console.log("TotalVntas:", TotalVntas);
TotalVntas += 0.50; // Esto es equivalente a TotalVntas = TotalVntas + 50.25
console.log("TotalVntas después de agregar 0.50:", TotalVntas);